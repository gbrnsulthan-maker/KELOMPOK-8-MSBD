CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS lab11;

CREATE TABLE IF NOT EXISTS lab11.tenant (
 id integer PRIMARY KEY,
 nama text NOT NULL
);

CREATE TABLE IF NOT EXISTS lab11.pelanggan (
 id integer PRIMARY KEY,
 tenant_id integer NOT NULL REFERENCES lab11.tenant(id),
 nama text NOT NULL,
 nik text NOT NULL,
 surel text NOT NULL,
 lahir date NOT NULL,
 kota text NOT NULL,
 saldo numeric(14,2) NOT NULL DEFAULT 0,
 rekening text NOT NULL,
 rekening_enc bytea
);

CREATE TABLE IF NOT EXISTS lab11.akun (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nama_peran text UNIQUE NOT NULL,
 keterangan text
);

CREATE TABLE IF NOT EXISTS lab11.transaksi (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id integer NOT NULL REFERENCES lab11.tenant(id),
 pelanggan_id integer NOT NULL REFERENCES lab11.pelanggan(id),
 jumlah numeric(14,2) NOT NULL,
 dibuat_pada timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lab11.jejak_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 waktu timestamptz NOT NULL DEFAULT clock_timestamp(),
 aktor text NOT NULL,
 aksi text NOT NULL,
 tabel_target text NOT NULL,
 kunci text NOT NULL,
 nilai_lama jsonb,
 nilai_baru jsonb
);

CREATE TABLE IF NOT EXISTS lab11.permintaan_hapus (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pelanggan_id integer NOT NULL,
 diminta_pada timestamptz NOT NULL DEFAULT now(),
 tenggat timestamptz NOT NULL DEFAULT (now() + interval '72 hours'),
 status text NOT NULL DEFAULT 'diterima'
);

